
import { useCallback } from "react";
import { MessageProcessor } from "./MessageProcessor";
import { useMessageManager } from "@/hooks/useMessageManager";
import { 
  uploadChatImage, 
  saveMessageToDb, 
  // callGeminiAI, // Now used in useAiChatHandler
  // fetchChatMessagesFromDb // Now used in useChatLoader
} from "@/services/chatApiService";
import { detectLanguageInPrompt } from "@/utils/languageDetector";
import { Message } from "@/types/chat";
import { useAiChatHandler } from "@/hooks/useAiChatHandler"; // New import
import { useChatLoader } from "@/hooks/useChatLoader";     // New import

interface ChatLogicProps {
  currentChatId: string | null;
  onMessagesChange: (messages: Message[]) => void;
  onLoadingChange: (loading: boolean) => void;
}

const WELCOME_MESSAGE: Message = {
  content: "Welcome to CHICHA AI! How can I help you today? I can chat, answer questions about images you upload, or search the web if you type '/search your query'.",
  isBot: true,
};

export const useChatLogic = ({ currentChatId, onMessagesChange, onLoadingChange }: ChatLogicProps) => {
  const {
    messages,
    isLoading,
    addMessage,
    addProcessingMessage,
    replaceLastMessage,
    removeLastMessageIfProcessing,
    setMessagesList,
    setIsLoadingState,
  } = useMessageManager({ 
    initialMessages: [WELCOME_MESSAGE], 
    onMessagesChange, 
    onLoadingChange 
  });

  const { processWithMainAI } = useAiChatHandler({
    currentChatId,
    addMessage,
    addProcessingMessage,
    replaceLastMessage,
    removeLastMessageIfProcessing,
    setIsLoadingState,
  });

  const { loadChat } = useChatLoader({
    setIsLoadingState,
    setMessagesList,
    welcomeMessage: WELCOME_MESSAGE,
  });

  const messageProcessor = MessageProcessor({
    onSend: useCallback((messageContentFromHandler: string, _options?: { targetLanguage?: string }) => {
      // This onSend is for messages generated by handlers within MessageProcessor (e.g. search results)
      console.log("ChatLogic (MessageProcessor.onSend): Adding bot/handler message:", { content: messageContentFromHandler, isBot: true });
      addMessage({ content: messageContentFromHandler, isBot: true });
    }, [addMessage])
  });

  const handleImageUpload = async (file: File) => {
    // No need to set loading state here, as it's usually tied to message sending
    return uploadChatImage(file);
  };

  const handleSendMessage = async (content: string, options?: { targetLanguage?: string }) => {
    if (!currentChatId) {
      console.error("ChatLogic (handleSendMessage): currentChatId is null. Cannot send message.");
      // Optionally, inform the user via a message, though this case should ideally be prevented by UI logic
      addMessage({ content: "Error: No active chat selected. Cannot send message.", isBot: true });
      return;
    }

    const userMessage: Message = { content, isBot: false };
    console.log("ChatLogic (handleSendMessage): Adding user message:", userMessage);
    addMessage(userMessage);
    await saveMessageToDb(currentChatId, content, false); // Save user's message

    const detectedLanguage = options?.targetLanguage || detectLanguageInPrompt(content);

    // Check for /search command specifically (or other commands MessageProcessor handles)
    const searchMatch = content.match(/^\/search\s+(.+)/i);
    if (searchMatch) {
      console.log("ChatLogic (handleSendMessage): Processing search command with MessageProcessor:", content);
      // MessageProcessor will call its onSend to add the bot's response.
      await messageProcessor.processMessage(content, [], detectedLanguage);
      return; 
    }
    
    // Try other handlers via MessageProcessor
    console.log("ChatLogic (handleSendMessage): Trying other handlers with MessageProcessor:", content);
    const wasProcessedByHandler = await messageProcessor.processMessage(content, [], detectedLanguage);
    if (wasProcessedByHandler) {
      console.log("ChatLogic (handleSendMessage): Message processed by a handler.");
      // If a handler processed it, its response was sent via MessageProcessor's onSend.
      return;
    }

    // If not processed by any specific handler, send to the main AI using the new hook.
    console.log("ChatLogic (handleSendMessage): No handler processed. Sending to main AI via useAiChatHandler.");
    await processWithMainAI(content, detectedLanguage);
  };

  const resetMessages = () => {
    console.log("ChatLogic: Resetting messages to WELCOME_MESSAGE.");
    setMessagesList([WELCOME_MESSAGE]);
  };

  return {
    messages,
    isLoading,
    handleSendMessage,
    loadChat, // from useChatLoader
    resetMessages,
    handleImageUpload
  };
};
